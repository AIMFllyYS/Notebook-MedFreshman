def transform_file(path: Path) -> str:
    file_id = path.stem
    content = path.read_text(encoding="utf-8")

    # 不处理已经包含大量指令的文件（如样章）
    if "::timeline" in content or "::memory" in content:
        return content

    content = add_timeline(content, file_id)
    content = add_concept_cards(content, file_id)
    content = wrap_conclusion_lists(content)
    content = add_keypoints(content, file_id)
    content = add_memory(content, file_id)
    return content


def main() -> None:
    files = sorted(TEXTBOOK_DIR.glob("*.md"))
    for path in files:
        transformed = transform_file(path)
        path.write_text(transformed, encoding="utf-8")
        print(f"Transformed {path.name}")


if __name__ == "__main__":
    main()
