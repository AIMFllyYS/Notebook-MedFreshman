def wrap_conclusion_lists(content: str) -> str:
    """将末尾的“第一、第二、第三……”或“一是、二是……”结论列表包装成 keypoint。"""
    # 简单策略：将“第一，”开头、连续多行的段落包装成 keypoint
    pattern = re.compile(
        r"(?P<body>(?:^第[一二三四五六七八九十]+[，、].+(?:\n|$))+)",
        re.MULTILINE,
    )

    def repl(match: re.Match) -> str:
        body = match.group("body").strip()
        if not body or len(body) < 50:
            return body
        return f":::keypoint{{label=核心结论}}\n{body}\n:::"

    return pattern.sub(repl, content)


def add_timeline(content: str, file_id: str) -> str:
    """在文件顶部 H1 之后添加时间轴。"""
    events = chapter_events(file_id)
    if not events:
        return content
    timeline_body = "\n".join(f"- {e}" for e in events)
    timeline = f":::timeline{{period=本章概览}}\n{timeline_body}\n:::\n"

    lines = content.split("\n")
    if len(lines) >= 2 and lines[0].startswith("# "):
        return lines[0] + "\n\n" + timeline + "\n" + "\n".join(lines[1:])
    return timeline + "\n" + content


def add_memory(content: str, file_id: str) -> str:
    """在文件末尾添加 memory 必背清单。"""
    items = chapter_memory(file_id)
    if not items:
        return content
    body = "\n".join(f"- {item}" for item in items)
    memory = f"\n:::memory{{label=本节必背要点}}\n{body}\n:::\n"
    return content.rstrip() + memory


